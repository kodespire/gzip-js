// Runs after `npm install`. Replaces the file:../.. link to the repo with the package
// as npm would publish it (`npm pack` of the repo root), so the app builds from the
// published files and autolinking sees exactly what users get. Also writes the test
// fixtures the self-test needs as a JS module (React Native has no file system API),
// and what the package's WebAssembly build makes of them, which the native module on
// the device must match byte for byte.
import { execFileSync } from 'node:child_process';
import { existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, rmSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(app, '..', '..');

if (!existsSync(join(repo, 'dist', 'entry-react-native.js'))) {
  console.error('gzip-js is not built. In the repo root, run `npm run build:wasm && npm run build:ts` first.');
  process.exit(1);
}

const target = join(app, 'node_modules', '@kodespire', 'gzip-js');
const tmp = mkdtempSync(join(tmpdir(), 'gzip-js-pack-'));
try {
  const packed = JSON.parse(execFileSync('npm', ['pack', '--json', '--pack-destination', tmp], { cwd: repo, encoding: 'utf8' }));
  const tarball = join(tmp, packed[0].filename);
  // Remove the link itself, never what it points to.
  if (existsSync(target) && lstatSync(target).isSymbolicLink()) unlinkSync(target);
  else rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  execFileSync('tar', ['-xzf', tarball, '-C', target, '--strip-components=1']);
  console.log(`installed ${packed[0].filename} (${packed[0].entryCount} files, ${packed[0].size} bytes packed)`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

const fixtures = [
  'corpus.txt',
  'corpus.9.gz',
  'corpus.multi.gz',
  'corpus.name.gz',
  'corpus.zlib',
  'corpus.small-window.zlib',
  'corpus.raw',
  'empty.gz',
  'dict.bin',
  'record.json',
  'record.dict.zlib',
  'record.dict.raw',
];
const fixture = (name) => readFileSync(join(repo, 'test', 'fixtures', name));
const entries = fixtures.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(fixture(name).toString('base64'))},`);

// Reference outputs from the WebAssembly build of the installed package, as
// [input fixture, options, length, FNV-1a of the output]. The dictionary is dict.bin.
const wasm = await import(pathToFileURL(join(target, 'dist', 'entry-wasm.js')).href);
const FORMATS = ['gzip', 'zlib', 'deflate-raw'];
const cases = [];
for (const format of FORMATS) {
  for (const level of [0, 1, 6, 9]) cases.push(['corpus.txt', { format, level }]);
  for (const strategy of ['filtered', 'huffman-only', 'rle', 'fixed']) cases.push(['corpus.txt', { format, strategy }]);
  cases.push(['corpus.txt', { format, level: 9, windowBits: 9, memLevel: 1 }]);
  cases.push(['corpus.txt', { format, level: 3, windowBits: 12, memLevel: 9 }]);
  cases.push(['empty', { format }]);
}
for (const format of ['zlib', 'deflate-raw']) cases.push(['record.json', { format, level: 9, dictionary: true }]);

function fnv1a(bytes) {
  let h = 0x811c9dc5;
  for (const b of bytes) h = Math.imul(h ^ b, 0x01000193) >>> 0;
  return h;
}

const references = cases.map(([input, options]) => {
  const data = input === 'empty' ? new Uint8Array(0) : fixture(input);
  const packed = wasm.compressSync(data, options.dictionary ? { ...options, dictionary: fixture('dict.bin') } : options);
  return [input, options, packed.length, fnv1a(packed)];
});
if (wasm.activeBackend() !== 'wasm') throw new Error('references must come from WebAssembly');

writeFileSync(
  join(app, 'selftest', 'fixtures.generated.js'),
  '// Generated by scripts/prepare.mjs from test/fixtures (base64) and the package\'s\n' +
    `// WebAssembly build (zlib ${wasm.ZLIB_VERSION}). Do not edit.\n` +
    `export default {\n${entries.join('\n')}\n};\n\n` +
    `export const references = ${JSON.stringify(references)};\n`,
);
console.log(`wrote ${fixtures.length} fixtures and ${references.length} WebAssembly reference outputs`);
